"""Generate the S3 Jack Hat schematic (KiCad 10) from a netlist-style description.

Written for Pulsar. Usage:  python3 tools/gen_schematic.py   (from hardware/s3-jack-hat/)

The symbol/layout engine below the part list is copied from
hardware/s3-hat/tools/gen_schematic.py (the parked, larger hat).

Writes s3-jack-hat.kicad_sch, s3-jack-hat.kicad_sym and the project library
tables. Every pin is wired by a short stub ending in a net label, so
connectivity is by name. Unused pins get a no-connect flag. The Hat2 header's
pad -> signal map comes from hat2.py (the one orientation choice).
"""
